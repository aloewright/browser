"""Stages K-O bundled extensions and emits the C++ list the loader uses.

Each extension directory is copied to <out_dir>/<name>. Component extensions
need a manifest "key" for a stable ID; when the manifest has none, a fixed
key derived from the directory name is injected, so the ID is the same on
every build and machine.
"""

import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import sys

NAME_RE = re.compile(r'^[A-Za-z0-9_-]+$')
KEY_SALT = b'K-O bundled extension v1:'
RAW_DELIMITER = 'KO_MANIFEST'
# Chromium refuses very large manifests anyway; keep the header small.
MAX_MANIFEST_BYTES = 256 * 1024


def derive_key(name):
    """Base64 key bytes; Chromium only hashes them to get the ID."""
    return base64.b64encode(hashlib.sha256(KEY_SALT +
                                           name.encode()).digest()).decode()


def extension_id(key):
    digest = hashlib.sha256(base64.b64decode(key)).hexdigest()[:32]
    return ''.join(chr(ord('a') + int(c, 16)) for c in digest)


def load_manifest(source_dir):
    path = os.path.join(source_dir, 'manifest.json')
    if not os.path.isfile(path):
        raise ValueError(f'{source_dir}: no manifest.json')
    with open(path, 'rb') as f:
        data = f.read(MAX_MANIFEST_BYTES + 1)
    if len(data) > MAX_MANIFEST_BYTES:
        raise ValueError(f'{source_dir}: manifest.json is too large')
    manifest = json.loads(data.decode('utf-8-sig'))
    if not isinstance(manifest, dict):
        raise ValueError(f'{source_dir}: manifest.json is not an object')
    for field in ('name', 'version', 'manifest_version'):
        if field not in manifest:
            raise ValueError(f'{source_dir}: manifest.json lacks "{field}"')
    return manifest


def stage_extension(source_dir, out_dir):
    """Copies one extension and returns (name, id, manifest, inputs)."""
    source_dir = os.path.abspath(source_dir)
    name = os.path.basename(os.path.normpath(source_dir))
    if not NAME_RE.match(name):
        raise ValueError(f'{source_dir}: directory name must match '
                         '[A-Za-z0-9_-]+')
    manifest = load_manifest(source_dir)
    if not isinstance(manifest.get('key'), str) or not manifest['key']:
        manifest['key'] = derive_key(name)

    dest = os.path.join(out_dir, name)
    if os.path.lexists(dest):
        shutil.rmtree(dest)
    inputs = []

    def ignore(directory, entries):
        # Skip VCS data, hidden files and symlinks (they could point outside
        # the extension).
        skipped = []
        for entry in entries:
            full = os.path.join(directory, entry)
            if entry.startswith('.') or os.path.islink(full):
                skipped.append(entry)
            elif os.path.isfile(full):
                inputs.append(full)
        return skipped

    shutil.copytree(source_dir, dest, ignore=ignore)
    with open(os.path.join(dest, 'manifest.json'), 'w', encoding='utf-8') as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
        f.write('\n')
    os.utime(dest)
    return name, extension_id(manifest['key']), manifest, inputs


def cpp_raw_string(text):
    if ')' + RAW_DELIMITER + '"' in text:
        raise ValueError('manifest contains the raw string delimiter')
    return f'R"{RAW_DELIMITER}({text}){RAW_DELIMITER}"'


def write_header(path, extensions):
    lines = [
        '// Generated by prepare_bundled_extensions.py. Do not edit.',
        '',
        '#ifndef BRAVE_COMPONENTS_KO_BUNDLED_EXTENSIONS_'
        'KO_BUNDLED_EXTENSIONS_H_',
        '#define BRAVE_COMPONENTS_KO_BUNDLED_EXTENSIONS_'
        'KO_BUNDLED_EXTENSIONS_H_',
        '',
        '#include <array>',
        '#include <string_view>',
        '',
        'namespace ko {',
        '',
        'struct BundledExtension {',
        '  // Folder under <resources>/ko_extensions.',
        '  std::string_view dir;',
        '  std::string_view id;',
        '  // manifest.json with a "key", so the ID is stable.',
        '  std::string_view manifest;',
        '};',
        '',
        'inline constexpr std::array<BundledExtension, '
        f'{len(extensions)}> kBundledExtensions = ' +
        ('{};' if not extensions else '{{'),
    ]
    for name, ext_id, manifest, _ in extensions:
        manifest_json = json.dumps(manifest, ensure_ascii=False)
        lines.append(f'    {{"{name}", "{ext_id}",')
        lines.append(f'     {cpp_raw_string(manifest_json)}}},')
    if extensions:
        lines.append('}};')
    lines += [
        '',
        '}  // namespace ko',
        '',
        '#endif  // BRAVE_COMPONENTS_KO_BUNDLED_EXTENSIONS_'
        'KO_BUNDLED_EXTENSIONS_H_',
        '',
    ]
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))


def write_depfile(path, target, inputs):
    def escape(p):
        return p.replace(' ', '\\ ')

    with open(path, 'w', encoding='utf-8') as f:
        f.write(escape(target) + ': ' + ' '.join(escape(i) for i in inputs) +
                '\n')


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out-dir', required=True)
    parser.add_argument('--header', required=True)
    parser.add_argument('--depfile')
    parser.add_argument('--depfile-target')
    parser.add_argument('dirs', nargs='*')
    args = parser.parse_args(argv)

    os.makedirs(args.out_dir, exist_ok=True)
    extensions = []
    names = set()
    try:
        for source_dir in args.dirs:
            staged = stage_extension(source_dir, args.out_dir)
            if staged[0] in names:
                raise ValueError(f'duplicate extension directory name '
                                 f'"{staged[0]}"')
            names.add(staged[0])
            extensions.append(staged)
    except (ValueError, json.JSONDecodeError, OSError) as e:
        print(f'K-O bundled extensions: {e}', file=sys.stderr)
        return 1

    write_header(args.header, extensions)
    if args.depfile:
        inputs = [i for ext in extensions for i in ext[3]]
        write_depfile(args.depfile, args.depfile_target or args.header, inputs)
    for name, ext_id, _, _ in extensions:
        print(f'K-O bundled extension {name}: {ext_id}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
