# Upstream's hobby compose uses moving tags (e.g. :master) for several Rust
# services. After a reviewed `pull`, freeze every image to the digest now on
# disk and use the result as an extra compose file:
#   doppler run -- ./pin-digests.sh > compose.pins.yml
set -eu
cd "$(dirname "$0")"
echo "# Generated by pin-digests.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
echo "services:"
docker compose --env-file versions.env -f docker-compose.yml -f compose.ko.yml \
  config --format json |
  python3 -I -c 'import json, sys
for name, svc in sorted(json.load(sys.stdin)["services"].items()):
    if "image" in svc:
        print(name, svc["image"])' |
  while read -r svc image; do
    case "$image" in *@sha256:*) continue ;; esac
    digest=$(docker image inspect --format '{{index .RepoDigests 0}}' "$image")
    printf '  %s:\n    image: %s\n' "$svc" "$digest"
  done
